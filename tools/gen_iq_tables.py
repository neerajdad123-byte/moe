"""Write src/gguf_iq.h: the lookup grids of GGUF's IQ3_XXS / IQ3_S quants and the IQ sign table, taken from the
`gguf` Python package (llama.cpp's reference), for src/gguf.h's dequantizers.

  python tools/gen_iq_tables.py
"""
import numpy as np
import gguf.quants as q

def grid(c):
    c.init_grid()
    return np.asarray(c.grid).reshape(c.grid_shape).astype(np.uint8)

out = ["// Generated by tools/gen_iq_tables.py from the gguf Python package (llama.cpp's grids). Do not edit.", "#pragma once",
       "#include <cstdint>", ""]
for name, c in (("iq3xxs_grid", q.IQ3_XXS), ("iq3s_grid", q.IQ3_S)):
    g = grid(c)
    out.append(f"static const uint8_t {name}[{g.shape[0]}][4] = {{")
    for i in range(0, g.shape[0], 8):
        out.append("    " + ", ".join("{%s}" % ",".join(str(v) for v in row) for row in g[i:i + 8]) + ",")
    out.append("};")
ks = np.frombuffer(q.IQ2_XXS.ksigns, dtype=np.uint8)
out.append(f"static const uint8_t iq_ksigns[{len(ks)}] = {{")
for i in range(0, len(ks), 16):
    out.append("    " + ", ".join(str(v) for v in ks[i:i + 16]) + ",")
out.append("};")
open("src/gguf_iq.h", "w", newline="\n").write("\n".join(out) + "\n")
print("wrote src/gguf_iq.h")
