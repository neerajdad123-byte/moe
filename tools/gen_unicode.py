"""Generate src/unicode_tab.h: codepoint ranges for the Unicode classes the Qwen pre-tokenizer regex uses
(\\p{L}, \\p{M}, \\p{N}, \\s). Run once; the header is committed.

  python tools/gen_unicode.py
"""
import sys, unicodedata

def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and start is None: start = cp
        if not ok and start is not None: out.append((start, cp - 1)); start = None
    if start is not None: out.append((start, 0x10FFFF))
    return out

cat = lambda cp: unicodedata.category(chr(cp))
# \s as Oniguruma/Unicode: White_Space property
WS = {0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680, *range(0x2000, 0x200B), 0x2028, 0x2029, 0x202F, 0x205F, 0x3000}
tabs = {
    "L": ranges(lambda cp: cat(cp).startswith("L")),
    "M": ranges(lambda cp: cat(cp).startswith("M")),
    "N": ranges(lambda cp: cat(cp).startswith("N")),
    "S": ranges(lambda cp: cp in WS),
}
with open("src/unicode_tab.h", "w") as f:
    f.write(f"// Generated by tools/gen_unicode.py from Python {sys.version.split()[0]} unicodedata "
            f"(Unicode {unicodedata.unidata_version}). Do not edit.\n#pragma once\n#include <cstdint>\n\n")
    for k, r in tabs.items():
        f.write(f"static const uint32_t UNI_{k}[][2] = {{\n")
        for i in range(0, len(r), 6):
            f.write("    " + ", ".join(f"{{0x{a:X}, 0x{b:X}}}" for a, b in r[i:i + 6]) + ",\n")
        f.write("};\n\n")
print({k: len(v) for k, v in tabs.items()})
